import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { see, shot, setWindowSize, startConnectedDesktop, type ConnectedDesktop } from './fixtures'

describe('ACP choices in agent settings', () => {
  let ctx: ConnectedDesktop
  const control = (id: string) => ctx.desktopPage.getByTestId(id)
  beforeAll(async () => {
    ctx = await startConnectedDesktop({ title: 'Agent choices' })
    while (await control('balloon-close').isVisible()) await control('balloon-close').click()
    const centre = await ctx.desktop.openApp('control-centre')
    await centre.getByTestId('control-centre-page-agents').click()
    await control('agents-row').filter({ hasText: 'Scripted Agent' }).click()
    await control('agents-edit').click()
  })
  afterAll(async () => { await ctx?.app.close() })

  it('loads this agent’s ACP models and modes, and persists their ids', async () => {
    await control('agent-model-button').click()
    await see.count(control('agent-model-option-sonnet'), 0)
    await shot(ctx.desktopPage, 'agent-choices-before-load')
    await control('agent-model-option-').click()
    await control('agents-dialog-load-choices').click()
    await see.text(control('agents-dialog-choices-status'), 'Loaded 2 models and 2 modes')
    await control('agent-model-button').click()
    await see.text(control('agent-model-option-scripted-2'), 'Scripted 2')
    await shot(ctx.desktopPage, 'agent-choices-normal')
    await control('agent-model-option-scripted-2').click()
    await control('agent-mode-button').click()
    await control('agent-mode-option-plan').click()
    await control('dialog-button-ok').click()
    await see.gone(control('agents-dialog'))
    const row = control('agents-row').filter({ hasText: 'Scripted Agent' })
    await see.text(row, 'scripted-2')
    await see.text(row, 'plan')
    await control('agents-edit').click()
    await see.eventually(async () => expect(await control('agent-model-input').inputValue()).toBe('scripted-2'))
  })

  it('supports keyboard selection, a maximized app and a small desktop', async () => {
    await control('agents-dialog-load-choices').click()
    await see.text(control('agents-dialog-choices-status'), 'Loaded 2 models and 2 modes')
    await control('agent-model-input').press('ArrowDown')
    await control('agent-model-input').press('Enter')
    await see.visible(control('agents-dialog'))
    await control('agent-model-input').press('ArrowDown')
    await control('agent-model-input').press('Escape')
    await see.visible(control('agents-dialog'))
    await control('dialog-button-cancel').click()
    await control('window-control-centre').getByTestId('window-maximize').click()
    await control('agents-edit').click()
    await control('agents-dialog-load-choices').click()
    await see.text(control('agents-dialog-choices-status'), 'Loaded 2 models and 2 modes')
    await control('agent-model-button').click()
    await shot(ctx.desktopPage, 'agent-choices-maximized')
    await control('agent-model-option-scripted-2').click()
    await setWindowSize(ctx.app, ctx.desktopPage, 900, 600)
    await control('connbar-pin').click()
    await control('agent-model-button').click()
    await shot(ctx.desktopPage, 'agent-choices-small')
    const option = await control('agent-model-option-scripted-2').boundingBox()
    expect(option).not.toBeNull()
    expect(option!.y + option!.height).toBeLessThanOrEqual(600)
    await control('agent-model-option-scripted-2').click()
  })

  it('invalidates choices when the launch command changes and reports discovery failure', async () => {
    await control('agents-dialog-command').fill('agentxp-no-such-command')
    await control('agent-model-button').click()
    await see.count(control('agent-model-option-scripted-1'), 0)
    await see.visible(control('agent-model-option-scripted-2'))
    await control('agent-model-option-scripted-2').click()
    await control('agents-dialog-load-choices').click()
    await see.text(control('agents-dialog-choices-status'), 'Could not load choices')
    await shot(ctx.desktopPage, 'agent-choices-error')
  })
})
