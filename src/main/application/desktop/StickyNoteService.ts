import type { Bounds, OpenedBy, StickyColor, StickyNoteDto } from '@shared/desktop'
import type { Id } from '@shared/models'
import type { StickyNotePatch, StickyNoteRepository } from '../../domain/repositories/sticky-note-repository'
import { AppError, required } from '../errors'
import type { EventPublisher } from '../ports'

export const STICKY_COLORS: readonly StickyColor[] = ['yellow', 'blue', 'green', 'pink', 'purple', 'white']
const NOTE_SIZE = { width: 240, height: 200 }
const MAX_TEXT = 20_000

export interface StickyNoteServiceDeps {
  notes: StickyNoteRepository
  events: EventPublisher
  /** Recomputes and publishes the desktop state (it carries the notes). */
  desktops: { refresh(desktopId: Id): void }
}

export interface NewNoteOptions {
  author?: OpenedBy
  /** Makes the note mirror that chat's plan; its text is generated by the renderer. */
  planSessionId?: Id | null
  bounds?: Bounds
}

/** Sticky notes of a desktop: CRUD, `notes.changed` to the owning window and the desktop state for the agent. */
export class StickyNoteService {
  constructor(private readonly deps: StickyNoteServiceDeps) {}

  list(desktopId: Id): StickyNoteDto[] {
    return this.deps.notes.list(desktopId)
  }

  add(desktopId: Id, text: string, color: StickyColor = 'yellow', options: NewNoteOptions = {}): StickyNoteDto {
    this.checkText(text)
    this.checkColor(color)
    const planSessionId = options.planSessionId ?? null
    if (planSessionId !== null) {
      const existing = this.list(desktopId).find((n) => n.planSessionId === planSessionId)
      if (existing) return existing
    }
    const count = this.list(desktopId).length
    const note = this.deps.notes.create({
      desktopId,
      text,
      color,
      bounds: options.bounds ?? { x: 40 + (count % 8) * 28, y: 40 + (count % 8) * 28, ...NOTE_SIZE },
      planSessionId,
      author: options.author ?? 'user'
    })
    this.changed(desktopId)
    return note
  }

  update(id: Id, patch: StickyNotePatch): StickyNoteDto {
    required(this.deps.notes.get(id), 'Note')
    if (patch.text !== undefined) this.checkText(patch.text)
    if (patch.color !== undefined) this.checkColor(patch.color)
    const note = required(this.deps.notes.update(id, patch), 'Note')
    this.changed(note.desktopId)
    return note
  }

  remove(id: Id): void {
    const note = required(this.deps.notes.get(id), 'Note')
    this.deps.notes.remove(id)
    this.changed(note.desktopId)
  }

  private changed(desktopId: Id): void {
    this.deps.events.publish('notes.changed', { desktopId, notes: this.list(desktopId) })
    this.deps.desktops.refresh(desktopId)
  }

  private checkText(text: string): void {
    if (text.length > MAX_TEXT) throw new AppError(`A note holds at most ${MAX_TEXT} characters`)
  }

  private checkColor(color: string): void {
    if (!STICKY_COLORS.includes(color as StickyColor)) throw new AppError(`Unknown note colour "${color}". Use one of: ${STICKY_COLORS.join(', ')}.`)
  }
}
